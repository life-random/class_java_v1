package ch05;

public class Operation5 {
    public static void main(String[] args) {
        int num1 = 5;
        int num2 = 3;

        //                  5  >  3
        boolean result1 = num1 > num2; // true
        System.out.println("result1 : " + result1);

        System.out.println(num1 > num2); // true
        System.out.println(num1 < num2); // false
        System.out.println(num1 >= num2); // true
        System.out.println(num1 <= num2); // false
        System.out.println(num1 == num2); // false
        System.out.println(num1 != num2); // true


    } // end of main

} // end of class
